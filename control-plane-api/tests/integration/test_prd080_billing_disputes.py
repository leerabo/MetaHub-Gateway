@pytest.mark.anyio
async def test_request_scope_create_replay_hold_conflict_and_frozen_outbox(
    control_fixture: ControlFixture,
) -> None:
    charges = _add_charges(
        control_fixture,
        (("request_create", "2026-08-01T01:00:00Z"),),
    )
    charge = charges["request_create"]
    app = _build_app()
    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://control") as client:
        admin = await _login(
            client,
            email=control_fixture.admin_email,
            password=ADMIN_PASSWORD,
        )
        created_response = await _create_request_dispute(
            client,
            admin,
            charge,
            key="prd080-create-request-key",
            request_id="req_prd080_create_request",
            reason="Ｓynthetic request charge requires review",
        )
        created = _assert_private(
            created_response,
            status_code=201,
            request_id="req_prd080_create_request",
        )
        _assert_mutation_shape(created)
        replay_response = await _create_request_dispute(
            client,
            admin,
            charge,
            key="prd080-create-request-key",
            request_id="req_prd080_create_replay",
        )
        replay = _assert_private(
            replay_response,
            status_code=200,
            request_id="req_prd080_create_replay",
        )
        conflict_response = await _create_request_dispute(
            client,
            admin,
            charge,
            key="prd080-create-request-key",
            request_id="req_prd080_create_conflict",
            reason="A different intent must not reuse the key",
        )
        _assert_private(
            conflict_response,
            status_code=409,
            request_id="req_prd080_create_conflict",
            code="billing_dispute.idempotency_conflict",
        )
        hold_response = await _create_request_dispute(
            client,
            admin,
            charge,
            key="prd080-create-second-key",
            request_id="req_prd080_hold_conflict",
        )
        _assert_private(
            hold_response,
            status_code=409,
            request_id="req_prd080_hold_conflict",
            code="billing_dispute.hold_conflict",
        )

    dispute = created["dispute"]
    summary = dispute["summary"]
