async def _login(
    client: AsyncClient,
    *,
    email: str,
    password: str,
    tenant_slug: str = "default",
) -> str:
    response = await client.post(
        "/auth/login",
        json={"tenant_slug": tenant_slug, "email": email, "password": password},
    )
    assert response.status_code == 200, response.text
    return str(response.json()["access_token"])


def _headers(
    token: str,
    request_id: str,
    *,
    idempotency_key: str | None = None,
) -> dict[str, str]:
    result = {"Authorization": f"Bearer {token}", "X-Request-ID": request_id}
    if idempotency_key is not None:
        result["Idempotency-Key"] = idempotency_key
    return result


def _assert_private(
    response: Response,
    *,
    status_code: int,
    request_id: str,
    code: str | None = None,
) -> dict[str, Any]:
    assert response.status_code == status_code, response.text
    assert response.headers["cache-control"] == "no-store, private"
    payload = response.json()
    assert payload["request_id"] == response.headers["x-request-id"]
    assert payload["trace_id"] == response.headers["x-trace-id"]
    assert payload["request_id"].startswith("req_")
    assert payload["trace_id"].startswith("trc_")
    assert payload["request_id"] != request_id
    assert payload["trace_id"] != request_id
    if code is not None:
        assert payload["code"] == code
    return payload


def _assert_summary_shape(summary: dict[str, Any]) -> None:
    assert set(summary) == SUMMARY_KEYS
    assert set(summary["created_by"]) == ACTOR_KEYS
    if summary["reviewer"] is not None:
        assert set(summary["reviewer"]) == ACTOR_KEYS


def _assert_detail_shape(detail: dict[str, Any]) -> None:
    assert set(detail) == DETAIL_KEYS
    _assert_summary_shape(detail["summary"])
    assert all(set(item) == ITEM_KEYS for item in detail["items"])
    assert all(set(item["hold"]) == HOLD_KEYS for item in detail["items"])
    assert all(
        item["adjustment_link"] is None or set(item["adjustment_link"]) == LINK_KEYS
        for item in detail["items"]
    )
    assert all(set(hold) == HOLD_KEYS for hold in detail["holds"])
    assert all(set(link) == LINK_KEYS for link in detail["adjustment_links"])
    assert all(set(transition) == TRANSITION_KEYS for transition in detail["transitions"])
    assert set(detail["event"]) == EVENT_KEYS


def _assert_mutation_shape(payload: dict[str, Any]) -> None:
    assert set(payload) == MUTATION_KEYS
    _assert_detail_shape(payload["dispute"])
    assert set(payload["transition"]) == TRANSITION_KEYS
    assert all(set(link) == LINK_KEYS for link in payload["adjustment_links"])


