// A task renderer can split a legacy fallback across inline elements during
// hydration. Keep the same fixed phrase boundary while allowing those static
// tags, so a user never sees "Connect a model 模型服务" after a partial redraw.
function localizeSplitTaskPhrases(html, locale) {
  const inlineTag = "(?:<(?:span|em|strong|small|b|i|code)\\b[^>]*>|</(?:span|em|strong|small|b|i|code)>)";
  const between = `(?:\\s|&nbsp;|${inlineTag})*`;
  const words = (value) => value.split(" ").join(between);
  const replacements = locale === "zh-CN"
    ? [
      [new RegExp(`${between}${words("Connect a model")}${between}模型服务${between}`, "gu"), "连接模型服务"],
      [new RegExp(`${between}模型服务${between}${words("and service credential")}${between}`, "gu"), "模型服务和服务凭据"],
      [new RegExp(`${between}Configure${between}模型服务${between}`, "gu"), "配置模型服务"],
      [new RegExp(`${between}Configure${between}模型${between}`, "gu"), "配置模型"],
    ]
    : [
      [new RegExp(`${between}${words("Connect a model")}${between}模型服务${between}`, "gu"), "Connect a model provider"],
      [new RegExp(`${between}模型服务${between}${words("and service credential")}${between}`, "gu"), "Provider and service credential"],
      [new RegExp(`${between}Configure${between}模型服务${between}`, "gu"), "Configure provider"],
      [new RegExp(`${between}Configure${between}模型${between}`, "gu"), "Configure models"],
    ];
  return replacements.reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), html);
}

function localizeChineseTextNodes(html) {
  return html.replace(/>([^<>]+)</g, (match, text) => {
    const trimmed = text.trim();
    if (!trimmed) return match;
    // A text node can contain a model ID, provider name, or diagnostic JSON.
    // Only translate complete known UI labels; substring replacement corrupts
    // values such as "kimi-k2.7-code" and "QA Fake Endpoint".
    const localized = CHINESE_STATIC_TEXT.get(trimmed);
    if (!localized) return match;
    const leading = text.slice(0, text.length - text.trimStart().length);
    const trailing = text.slice(text.trimEnd().length);
    return `>${leading}${localized}${trailing}<`;
  });
}

/**
 * Project known static renderer literals for English sessions.
 *
 * This deliberately operates on HTML only at the final content boundary so
 * legacy feature renderers can be migrated incrementally. It is disabled for
 * every locale except en-US, preserving the established Chinese default.
 */
export function localizeConsoleStaticHtml(html, i18n) {
  if (typeof html !== "string") return html;
  if (i18n?.locale === "zh-CN") return localizeChineseTextNodes(localizeSplitTaskPhrases(html, "zh-CN"));
  if (i18n?.locale !== "en-US") return html;
  const localized = SORTED_TEXT.reduce((result, [source, target]) => result.replaceAll(source, target),
    localizeExactEnglishTextNodes(localizeSplitTaskPhrases(html, "en-US")));
  return localized
    .replace(/>(\s*)真实\s+(\d+)(\s*)</gu, ">$1Real $2$3<")
    .replace(/>(\s*)(\d+)\s*条(\s*)</gu, ">$1$2 records$3<")
    .replace(/(\d+) 个模型/g, "$1 model(s)")
    .replace(/(\d+) 个服务/g, "$1 provider(s)")
    .replace(/(\d+)\s*(?:把|个)\s*KEY/g, "$1 key(s)")
    // Generic Chinese counters can be left behind when their noun is
    // projected by an earlier replacement (for example `1 把active key(s)`
    // and `3 位Members`). Normalize the complete counter phrase so English
    // users never see a bilingual fragment.
    .replace(/(\d+)\s*(?:把|个)\s*active key\(s\)/g, "$1 active key(s)")
    .replace(/(\d+)\s*位\s*Members/g, "$1 members")
    .replace(/(\d+)\s*(?:条规则|条Rules)/g, "$1 rule(s)")
    .replace(/(\d+)\s*条策略/g, "$1 policy(s)")
    .replace(/(\d+) 位成员/g, "$1 member(s)");
}

