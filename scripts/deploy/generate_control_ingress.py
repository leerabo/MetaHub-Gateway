"""Generate the append-only control ingress retirement policy from its owner manifest."""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "infra" / "ingress" / "retired-console-routes.conf"


def render_retired_routes() -> str:
    # URI is decoded/normalized by Nginx. Retire every verb, including HEAD/OPTIONS,
    # and the trailing-slash redirect variant, without denying surviving children.
    source = ROOT / "control-plane-api/src/metahub_control/console_migration/manifest.py"
    module = ast.parse(source.read_text(encoding="utf-8"))
    manifest = next(
        ast.literal_eval(node.value)
        for node in module.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "LEGACY_ROUTE_MANIFEST"
                for target in node.targets)
    )
    # Old application images still publish their retired operations in OpenAPI.
    # API documentation remains reachable only on the private backend network.
    paths = sorted({path for _method, path in manifest} | {
        "/openapi.json", "/docs", "/docs/oauth2-redirect", "/redoc",
    })
    lines = [
        "# Generated by scripts/deploy/generate_control_ingress.py; do not edit.",
        "# Retirement epoch: PRD-147-v1. Never roll back with the application image.",
        "map $uri $metahub_retired_console_route {",
        "    default 0;",
    ]
    for path in paths:
        parts = re.split(r"(\{[a-z_]+\})", path)
        pattern = "".join("[^/]+" if part.startswith("{") else re.escape(part)
                          for part in parts)
        lines.append(f'    "~^{pattern}/?$" 1;')
    return "\n".join([*lines, "}", ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_retired_routes()
    if args.check:
        return 0 if OUTPUT.is_file() and OUTPUT.read_text(encoding="ascii") == expected else 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="ascii", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
